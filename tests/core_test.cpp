#include "core.hpp"
#include <cassert>
#include <iostream>

using namespace nigh;
static Asset media(int frames,bool video,bool audio) {
    Asset a;
    a.frames=frames; a.video=video?0:-1; a.audio=audio?1:-1;
    return a;
}
int main() {
    Project p;
    p.assets={media(120,true,true),media(72,true,false),media(90,false,true),media(60,false,true)};
    assert(add(p,0,0).index==0);
    assert(add(p,1,0).index==1);
    assert(length(p.seq)==192);
    assert(at(p.seq,Video,119).index==0);
    assert(at(p.seq,Video,120).index==1);
    assert(at(p.seq,Video,192).index==-1);
    assert(split(p.seq,Selection(Video,0),48));
    assert(!split(p.seq,Selection(Video,0),0));
    assert(p.seq.video[0]==Clip(0,0,48));
    assert(p.seq.video[1]==Clip(0,48,72));
    assert(move(p.seq,Selection(Video,0),3).index==2);
    assert(p.seq.video[2]==Clip(0,0,48));
    assert(trim(p,Selection(Video,2),true,10));
    assert(trim(p,Selection(Video,2),false,1024));
    assert(p.seq.video[2]==Clip(0,10,110));
    assert(erase(p.seq,Selection(Video,1)));
    assert(length(p.seq,Video)==182);
    assert(add(p,2,0).lane==Music);
    assert(add(p,3,44).index==1);
    assert(p.seq.music[1].pos==90);
    assert(split(p.seq,Selection(Music,0),25));
    assert(p.seq.music[1]==Clip(2,25,65,25));
    assert(!trim(p,Selection(Music,1),true,12)); // previous audio occupies the gap
    assert(trim(p,Selection(Music,1),true,35));
    assert(p.seq.music[1].pos==35 && p.seq.music[1].len==55);
    assert(move(p.seq,Selection(Music,1),160).index==2);
    assert(p.seq.music[2].pos==160 && p.seq.music[2].in==35);
    assert(length(p.seq,Music)==215);
    assert(length(p.seq)==215);
    assert(at(p.seq,Music,27).index==-1);
    assert(valid(p,true));
    p.seq.music[2].pos=12;
    assert(!valid(p,false));
    p.seq.music[2].pos=160;
    p.seq.video[0].asset=99;
    assert(!valid(p,false));
    p.seq.video[0].asset=0;
    p.seq.video[0].len=121;
    assert(!valid(p,true));
    p.seq.video[0].len=0;
    assert(!valid(p,false));
    assert(seconds(1)==L"0.041667");
    assert(seconds(71)==L"2.958333");
    assert(timecode(86400+1440+47)==L"01:01:01:23");
    Project max;
    max.assets={media(MaxFrames,true,false),media(1,true,false),media(MaxFrames,false,true)};
    assert(add(max,0,0).index==0);
    assert(add(max,1,0).index==-1);
    assert(add(max,2,999999).index==0);
    assert(add(max,2,0).index==-1);
    assert(valid(max,true));
    Project layered;
    layered.assets={media(96,true,true),media(60,true,false),media(120,false,true)};
    assert(place(layered,0,Video,0,10,50).index==0);
    assert(insertVideo(layered,1,17,3,12).index==1);
    assert(layered.seq.video[0].len==17 && layered.seq.video[2].in==27 && length(layered.seq,Video)==62);
    layered.seq.video[1].fx.dissolve=8;
    assert(place(layered,1,Overlay,20,7,9).index==0);
    assert(place(layered,0,Voice,10,4,12).index==0); // use only the audio of a video
    assert(place(layered,2,Overlay,0,0,30).index<0);
    assert(place(layered,2,Voice,15,0,12).index==1 && layered.seq.voice[1].pos==22);
    assert(layered.seq.overlay[0].fx.scale==42);
    Clip title(-1,0,14);
    title.title.text=L"Olá, edição";
    assert(paste(layered.seq,Titles,title,14).index==0);
    assert(trim(layered,Selection(Titles,0),true,-4));
    assert(layered.seq.titles[0].pos==10 && layered.seq.titles[0].in==0 && layered.seq.titles[0].len==18);
    assert(split(layered.seq,Selection(Titles,0),18) && layered.seq.titles[1].in==0);
    assert(move(layered.seq,Selection(Titles,1),28).index==1);
    assert(putMarker(layered.seq,29,L"Fim da transição"));
    assert(putMarker(layered.seq,2,L"Primeiro") && layered.seq.markers[0].frame==2);
    assert(putMarker(layered.seq,2,L"") && layered.seq.markers.size()==1);
    assert(setWorkEdge(layered.seq,false,9) && setWorkEdge(layered.seq,true,45));
    assert(!setWorkEdge(layered.seq,true,0));
    assert(layered.seq.workIn==9 && layered.seq.workOut==45);
    assert(valid(layered,true));
    Scene cross=sceneAt(layered.seq,20);
    assert(cross.main==&layered.seq.video[1] && cross.previous==&layered.seq.video[0] && cross.overlay && cross.title==0);
    assert(cross.mainOffset==3 && cross.overlayOffset==0 && cross.dissolve==8);
    assert(!sceneAt(layered.seq,25).dissolve);
    assert((sceneCuts(layered.seq,11,31)==std::vector<int>{11,17,18,20,25,28,29,31}));
    layered.seq.hideV2=true;
    assert(!sceneAt(layered.seq,21).overlay);
    assert((sceneCuts(layered.seq,11,31)==std::vector<int>{11,17,18,25,28,29,31}));
    assert(layered.seq==Sequence(layered.seq));
    layered.seq.video[0].fx.dissolve=1;
    assert(!valid(layered,false));
    layered.seq.video[0].fx.dissolve=0;
    layered.seq.titles[0].title.text.clear();
    assert(!valid(layered,false));
    Project still;
    still.assets={media(120,true,false)}; still.assets[0].still=true;
    assert(add(still,0,0).index==0);
    assert(trim(still,Selection(Video,0),false,121) && valid(still,true));
    assert(split(still.seq,Selection(Video,0),100) && trim(still,Selection(Video,1),true,-12));
    assert(valid(still,true) && length(still.seq)==233);
    std::cout<<"Core: ripple edits, six rows, titles, markers, export spans and model limits OK\n";
}
