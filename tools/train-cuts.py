#!/usr/bin/env python3
"""Train the small Nigh cut classifier on procedural frame triplets.

Only Python's standard library is required. Runtime inference is an integer
score over nine features. This validation set is synthetic, not a claim of
real-world accuracy. python3 tools/train-cuts.py [--check]
"""
import math
import random
import sys
from pathlib import Path

W, H = 16, 9
N = W * H


def clamp(n, lo, hi):
    return max(lo, min(n, hi))


def scene(rng, palette=None):
    palette = palette or [(rng.randrange(25, 231), rng.randrange(-150, 151)) for _ in range(4)]
    grid = [palette[0]] * N
    for color in palette[1:]:
        x, y = rng.randrange(W), rng.randrange(H)
        width, height = rng.randrange(3, W + 3), rng.randrange(2, H + 2)
        for j in range(height):
            for i in range(width):
                grid[((j + y) % H) * W + ((i + x) % W)] = color
    return tuple(zip(*grid)), palette


def transform(frame, rng, dx=0, dy=0, light=0, tint=0, noise=4):
    y, c = frame
    idx = [clamp(j - dy, 0, H - 1) * W + clamp(i - dx, 0, W - 1) for j in range(H) for i in range(W)]
    return ([clamp(y[k] + light + rng.randint(-noise, noise), 0, 255) for k in idx],
            [clamp(c[k] + tint + rng.randint(-noise, noise), -255, 255) for k in idx])


def diff(a, b):
    ay, ac = a
    by, bc = b
    avg = sum(ay) // N - sum(by) // N
    texture = min(sum(abs(ay[y * W + x] - by[(y + dy) * W + x + dx] - avg)
                      for y in range(1, H - 1) for x in range(1, W - 1))
                  for dy in range(-1, 2) for dx in range(-1, 2))
    return (sum(abs(x - y) for x, y in zip(ay, by)) // N,
            sum(abs(x - y) for x, y in zip(ac, bc)) // (2 * N), texture // ((W - 2) * (H - 2)))


def examples(seed, size):
    rng = random.Random(seed)
    for _ in range(size):
        base, colors = scene(rng)
        a = transform(base, rng)
        mode = rng.randrange(6)
        move = lambda: (rng.randint(-1, 1), rng.randint(-1, 1))
        if mode <= 1:
            other, _ = scene(rng, colors if mode == 1 else None)
            b = transform(other, rng, *move(), light=rng.randint(-15, 15))
            c = transform(other, rng, *move(), light=rng.randint(-15, 15))
            label = 1
            # Extremely similar random pairs are not useful hard cut examples.
            d = diff(a, b)
            if d[0] + d[1] + d[2] < 31:
                label = 0
        elif mode == 2:
            b = transform(base, rng, *move(), light=rng.randint(40, 150), tint=rng.randint(-35, 35))
            c = transform(base, rng, *move(), light=rng.randint(-8, 8))
            label = 0
        elif mode == 3:
            other, _ = scene(rng)
            b = transform(other, rng)
            c = transform(base, rng, *move())
            label = 0
        else:
            light = rng.randint(-38, 38)
            dx, dy = move()
            b = transform(base, rng, dx, dy, light=light, noise=8)
            c = transform(base, rng, dx * 2, dy * 2, light=light * 2, noise=8)
            label = 0
        yield (*diff(a, b), *diff(a, c), *diff(b, c)), label


def main():
    train = list(examples(20261118, 2200))
    check = list(examples(20261119, 500))
    w, b = [0.0] * 9, 0.0
    for i in range(26):
        for xs, label in train:
            features = [x / 64 for x in xs]
            z = clamp(b + sum(t * x for t, x in zip(w, features)), -20, 20)
            error = (label - 1 / (1 + math.exp(-z))) * (0.045 / (1 + i * 0.12))
            b += error
            for j, val in enumerate(features):
                w[j] += error * val
    weights, bias = [round(v * 4096 / 64) for v in w], round((b - 0.35) * 4096)
    confusion = [0] * 4
    for xs, label in check:
        taken = int(sum(xs[:3]) >= 28 and bias + sum(v * x for v, x in zip(weights, xs)) > 0)
        confusion[label * 2 + taken] += 1
    print('Validação sintética: TN, FP, FN, TP =', confusion)
    assert (confusion[0] + confusion[3]) * 100 >= 86 * len(check)
    data = ('// Generated by tools/train-cuts.py; see models/README.md.\n'
            '#pragma once\nnamespace nigh {\n'
            f'const int CutBias = {bias};\n'
            f'const int CutWeights[9] = {{{", ".join(map(str, weights))}}};\n'
            '}\n')
    target = Path(__file__).resolve().parent.parent / 'src' / 'cut_weights.hpp'
    if '--check' in sys.argv:
        assert target.read_text() == data, 'cut_weights.hpp está desatualizado'
    else:
        target.write_text(data)


if __name__ == '__main__':
    main()
